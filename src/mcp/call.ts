// callTool: one tools/call, with a measured duration and an explicit timeout.
import type { CallToolResult } from "@modelcontextprotocol/sdk/types.js";
import { CallRegistry, defaultCalls } from "./cancel.js";
import { StudioError, isRequestTimeout } from "./errors.js";
import type { Session } from "./session.js";

/** The SDK default is 60s, which outlives the 20s test budget and any patient user. */
export const DEFAULT_CALL_TIMEOUT_MS = 30_000;

export type ContentBlock = CallToolResult["content"][number];

/**
 * Exactly the fields of a tools/call response, plus `ms`. There is no `ok`: `isError` is the
 * single truth, and `isError: true` is a SUCCESSFUL JSON-RPC response, so it is returned, not thrown.
 */
export interface CallResult {
  content: ContentBlock[];
  structuredContent?: Record<string, unknown>;
  isError: boolean;
  /** Wall-clock duration measured here. The SDK reports no timing. */
  ms: number;
}

export interface CallOptions {
  /**
   * Generated by the CLIENT (see newCallId) and sent with the request. cancelCall(callId) aborts it.
   * Must be unique among calls in flight.
   */
  callId: string;
  /** Optional extra abort source, merged with cancelCall(callId). */
  signal?: AbortSignal;
  /** Request timeout in ms. Defaults to DEFAULT_CALL_TIMEOUT_MS. */
  timeout?: number;
  /** In-flight registry to use. Defaults to the process-wide one. */
  calls?: CallRegistry;
}

export async function callTool(
  session: Session,
  name: string,
  args: Record<string, unknown>,
  opts: CallOptions,
): Promise<CallResult> {
  const timeout = opts.timeout ?? DEFAULT_CALL_TIMEOUT_MS;
  const calls = opts.calls ?? defaultCalls;
  // Registered BEFORE the request is issued, so a cancel can arrive at any moment after this line.
  const controller = calls.register(opts.callId);
  const forward = (): void => controller.abort(opts.signal?.reason);
  if (opts.signal?.aborted) forward();
  else opts.signal?.addEventListener("abort", forward, { once: true });

  const started = performance.now();
  try {
    const res = await session.client.callTool({ name, arguments: args }, undefined, {
      timeout,
      signal: controller.signal,
    });
    const result: CallResult = {
      content: (res.content ?? []) as ContentBlock[],
      isError: res.isError === true,
      ms: Math.round(performance.now() - started),
    };
    if (res.structuredContent !== undefined) result.structuredContent = res.structuredContent as Record<string, unknown>;
    return result;
  } catch (err) {
    const ms = Math.round(performance.now() - started);
    // Order matters: the SDK reports ANY abort whose reason is not an McpError as RequestTimeout,
    // so our own controller must be checked first or every cancel would read as a timeout.
    if (controller.signal.aborted) throw new StudioError("cancelled", `${name} was cancelled after ${ms}ms`, { cause: err });
    if (isRequestTimeout(err)) throw new StudioError("timeout", `${name} timed out after ${timeout}ms`, { cause: err });
    throw err;
  } finally {
    opts.signal?.removeEventListener("abort", forward);
    calls.release(opts.callId);
  }
}
